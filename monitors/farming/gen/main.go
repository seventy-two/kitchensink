// Command gen writes runelite.go: RuneLite's farming data (what each
// patch's varbit values mean, how fast each crop grows, and where the
// patches are), read from the Time Tracking plugin's Java source at a fixed
// commit, so the monitor predicts patches exactly as RuneLite does.
//
// Run it from the farming package's directory with go generate. Bump
// commit to pick up new patches or crops.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"regexp"
	"strconv"
	"strings"
)

const (
	commit = "9fad2c588ca957ae47d883b09544725a796ed9fe"
	base   = "https://raw.githubusercontent.com/runelite/runelite/" + commit + "/"
	plugin = base + "runelite-client/src/main/java/net/runelite/client/plugins/timetracking/"
)

func main() {
	out := flag.String("o", "runelite.go", "file to write")
	flag.Parse()

	produceSrc := fetch(plugin + "farming/Produce.java")
	implSrc := fetch(plugin + "farming/PatchImplementation.java")
	worldSrc := fetch(plugin + "farming/FarmingWorld.java")
	varbitSrc := fetch(base + "runelite-api/src/main/java/net/runelite/api/gameval/VarbitID.java")

	produces := parseProduces(produceSrc)
	stages := map[string]int{}
	for _, p := range produces {
		stages[p.id] = p.stages
	}
	impls := parseImpls(implSrc, stages)
	regions := parseWorld(worldSrc, parseVarbits(varbitSrc))

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen from RuneLite %s; DO NOT EDIT.\n\n", commit[:12])
	b.WriteString(licence(produceSrc))
	b.WriteString("\npackage farming\n\n")
	b.WriteString("var produces = map[string]produce{\n")
	for _, p := range produces {
		fmt.Fprintf(&b, "%q: {Name: %q, Impl: %q, Tick: %d, Stages: %d, Regrow: %d, Harvests: %d},\n",
			p.id, p.name, p.impl, p.tick, p.stages, p.regrow, p.harvests)
	}
	b.WriteString("}\n\nvar implementations = map[string]implementation{\n")
	for _, im := range impls {
		fmt.Fprintf(&b, "%q: {Tab: %q, Name: %q, HealthCheck: %v, Rules: []rule{\n", im.id, im.tab, im.name, im.health)
		for _, r := range im.rules {
			fmt.Fprintf(&b, "{%d, %d, %q, %s, %d, %d},\n", r.lo, r.hi, r.produce, r.state, r.mul, r.add)
		}
		b.WriteString("}},\n")
	}
	b.WriteString("}\n\nvar regions = []region{\n")
	for _, r := range regions {
		fmt.Fprintf(&b, "{Name: %q, ID: %d, Definite: %v, Patches: []patch{\n", r.name, r.id, r.definite)
		for _, p := range r.patches {
			fmt.Fprintf(&b, "{Name: %q, Varbit: %d, Impl: %q},\n", p.name, p.varbit, p.impl)
		}
		b.WriteString("}},\n")
	}
	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("formatting: %v\n%s", err, b.Bytes())
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func fetch(url string) string {
	resp, err := http.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("%s: %s", url, resp.Status)
	}
	body, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	return string(body)
}

// licence turns the Java file's BSD licence header into a Go comment.
func licence(src string) string {
	end := strings.Index(src, "*/")
	var b strings.Builder
	b.WriteString("// The data below comes from RuneLite (github.com/runelite/runelite):\n//\n")
	for _, line := range strings.Split(src[:end], "\n") {
		line = strings.TrimSpace(strings.TrimLeft(strings.TrimSpace(line), "/*"))
		b.WriteString(strings.TrimRight("// "+line, " ") + "\n")
	}
	return b.String()
}

type produceDef struct {
	id, name, impl                 string
	tick, stages, regrow, harvests int
}

var produceRE = regexp.MustCompile(`(?m)^\t([A-Z_]+)\("([^"]+)",\s*(.*)\)[,;]?\s*(//.*)?$`)

// parseProduces reads the Produce enum. Its constructors take, after the
// name: (item, tick, stages), (impl, item, tick, stages), (contract, impl,
// item, tick, stages), or either of the last two plus (regrow, harvests).
func parseProduces(src string) []produceDef {
	var out []produceDef
	for _, m := range produceRE.FindAllStringSubmatch(src, -1) {
		args := strings.Split(m[3], ",")
		for i := range args {
			args[i] = strings.TrimSpace(args[i])
		}
		p := produceDef{id: m[1], name: m[2], harvests: 1}
		// Drop the contract number, if any, so the impl comes first.
		if len(args) > 0 && isInt(args[0]) {
			args = args[1:]
		}
		if len(args) > 0 && strings.HasPrefix(args[0], "PatchImplementation.") {
			p.impl = strings.TrimPrefix(args[0], "PatchImplementation.")
			args = args[1:]
		}
		// args: item, tick, stages[, regrow, harvests]
		switch len(args) {
		case 3:
			p.tick, p.stages = atoi(args[1]), atoi(args[2])
		case 5:
			p.tick, p.stages, p.regrow, p.harvests = atoi(args[1]), atoi(args[2]), atoi(args[3]), atoi(args[4])
		default:
			log.Fatalf("produce %s: can't read %q", p.id, m[3])
		}
		out = append(out, p)
	}
	if len(out) < 50 {
		log.Fatalf("only %d produces", len(out))
	}
	return out
}

type ruleDef struct {
	lo, hi   int
	produce  string
	state    string
	mul, add int
}

type implDef struct {
	id, tab, name string
	health        bool
	rules         []ruleDef
}

var (
	implRE   = regexp.MustCompile(`(?m)^\t([A-Z_]+)\(Tab\.([A-Z_]+), "([^"]*)", (true|false)\)`)
	condRE   = regexp.MustCompile(`if \(([^)]*)\)\s*\{[^{}]*?return new PatchState\(Produce\.([A-Z_]+), CropState\.([A-Z]+), ([^;]*)\);`)
	rangeRE  = regexp.MustCompile(`^value >= (\d+) && value <= (\d+)$`)
	equalRE  = regexp.MustCompile(`^value == (\d+)$`)
	stagesRE = regexp.MustCompile(`Produce\.([A-Z_]+)\.getStages\(\)`)
	stateGo  = map[string]string{"GROWING": "growing", "HARVESTABLE": "harvestable", "DISEASED": "diseased", "DEAD": "dead", "EMPTY": "empty", "FILLING": "filling"}
)

// parseImpls reads PatchImplementation: each patch type's forVarbitValue,
// a run of "if (value in range) return new PatchState(produce, state,
// stage)", where stage is linear in value.
func parseImpls(src string, stages map[string]int) []implDef {
	locs := implRE.FindAllStringSubmatchIndex(src, -1)
	var out []implDef
	for i, l := range locs {
		end := len(src)
		if i+1 < len(locs) {
			end = locs[i+1][0]
		}
		im := implDef{id: src[l[2]:l[3]], tab: src[l[4]:l[5]], name: src[l[6]:l[7]], health: src[l[8]:l[9]] == "true"}
		body := src[l[1]:end]
		for _, m := range condRE.FindAllStringSubmatch(body, -1) {
			state, ok := stateGo[m[3]]
			if !ok {
				log.Fatalf("%s: crop state %s", im.id, m[3])
			}
			expr := stagesRE.ReplaceAllStringFunc(m[4], func(s string) string {
				n, ok := stages[stagesRE.FindStringSubmatch(s)[1]]
				if !ok {
					log.Fatalf("%s: unknown produce in %q", im.id, s)
				}
				return strconv.Itoa(n)
			})
			add, mul := linear(expr, 0), linear(expr, 1)-linear(expr, 0)
			for _, cond := range strings.Split(m[1], "||") {
				cond = strings.TrimSpace(cond)
				r := ruleDef{produce: m[2], state: state, mul: mul, add: add}
				if mm := rangeRE.FindStringSubmatch(cond); mm != nil {
					r.lo, r.hi = atoi(mm[1]), atoi(mm[2])
				} else if mm := equalRE.FindStringSubmatch(cond); mm != nil {
					r.lo, r.hi = atoi(mm[1]), atoi(mm[1])
				} else {
					log.Fatalf("%s: can't read condition %q", im.id, cond)
				}
				im.rules = append(im.rules, r)
			}
		}
		if n, read := strings.Count(body, "new PatchState("), len(condRE.FindAllString(body, -1)); n != read {
			log.Fatalf("%s: read %d of %d states", im.id, read, n)
		}
		out = append(out, im)
	}
	if len(out) < 20 {
		log.Fatalf("only %d patch implementations", len(out))
	}
	return out
}

// linear evaluates a sum of integers and "value", e.g. "15 + value - 161".
func linear(expr string, value int) int {
	total, sign := 0, 1
	for _, tok := range strings.Fields(strings.NewReplacer("+", " + ", "-", " - ").Replace(expr)) {
		switch tok {
		case "+":
			sign = 1
		case "-":
			sign = -1
		case "value":
			total += sign * value
		default:
			if !isInt(tok) {
				log.Fatalf("can't evaluate %q", expr)
			}
			total += sign * atoi(tok)
		}
	}
	return total
}

type patchDef struct {
	name   string
	varbit int
	impl   string
}

type regionDef struct {
	name     string
	id       int
	definite bool
	patches  []patchDef
}

var (
	regionRE = regexp.MustCompile(`new FarmingRegion\("([^"]+)", (\d+), (true|false),`)
	patchRE  = regexp.MustCompile(`new FarmingPatch\("([^"]*)", VarbitID\.([A-Z0-9_]+), PatchImplementation\.([A-Z_]+)`)
	varbitRE = regexp.MustCompile(`int (FARMING_TRANSMIT_[A-Z0-9]+) = (\d+);`)
)

func parseVarbits(src string) map[string]int {
	out := map[string]int{}
	for _, m := range varbitRE.FindAllStringSubmatch(src, -1) {
		out[m[1]] = atoi(m[2])
	}
	return out
}

// parseWorld reads FarmingWorld's regions and their patches, in order.
func parseWorld(src string, varbits map[string]int) []regionDef {
	locs := regionRE.FindAllStringSubmatchIndex(src, -1)
	var out []regionDef
	for i, l := range locs {
		end := len(src)
		if i+1 < len(locs) {
			end = locs[i+1][0]
		}
		r := regionDef{name: src[l[2]:l[3]], id: atoi(src[l[4]:l[5]]), definite: src[l[6]:l[7]] == "true"}
		for _, m := range patchRE.FindAllStringSubmatch(src[l[1]:end], -1) {
			v, ok := varbits[m[2]]
			if !ok {
				log.Fatalf("%s: unknown varbit %s", r.name, m[2])
			}
			r.patches = append(r.patches, patchDef{name: m[1], varbit: v, impl: m[3]})
		}
		out = append(out, r)
	}
	if len(out) < 30 {
		log.Fatalf("only %d regions", len(out))
	}
	return out
}

func isInt(s string) bool {
	_, err := strconv.Atoi(s)
	return err == nil
}

func atoi(s string) int {
	n, err := strconv.Atoi(s)
	if err != nil {
		log.Fatalf("not a number: %q", s)
	}
	return n
}
